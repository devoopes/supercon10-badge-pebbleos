"""Generate lut_b.h, the panel's short waveform, from the badge firmware.

The table is the badge team's (firmware/badge/data/rendered_luts.py in
third_party/billboard_badge/2026-Billboard_Badge). It is read as text, not
run: the 400 bytes of `lutb_base`, 5 tables x 10 groups x 8 bytes.

usage: gen_lut.py rendered_luts.py lut_b.h
"""

import re
import sys

NAME = "lutb_base"
SIZE = 400


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()
    m = re.search(rf"^{NAME}\s*=\s*\[(.*?)\]", text, re.S | re.M)
    if not m:
        sys.exit(f"{src}: no {NAME}")
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]{1,2}\b", m.group(1))]
    if len(values) != SIZE:
        sys.exit(f"{src}: {NAME} has {len(values)} bytes, not {SIZE}")

    lines = [
        "// Generated by gen_lut.py from the badge firmware's rendered_luts.py.",
        "// Driver-B (B1 panel) short waveform, 5 tables x 10 groups x 8 bytes.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"static const uint8_t LUT_B_BASE[{SIZE}] = {{",
    ]
    for t in range(5):
        lines.append(f"  // Table {t}")
        for g in range(10):
            row = values[t * 80 + g * 8 : t * 80 + g * 8 + 8]
            lines.append("  " + ", ".join(f"0x{v:02x}" for v in row) + ",")
    lines.append("};")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
